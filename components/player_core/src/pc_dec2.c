#include <string.h>
#include "pc/pc_dec2.h"

/* Halfband FIR: PC_DEC2_TAPS (101) taps, every other tap zero except the centre. Coefficients: python3 -I tools/gen/gen_halfband.py 49
 * (the script raises 49 -> 53 ... -> 101 until 90 dB holds, with 20 kHz also inside the passband at 88.2 kHz in; the table below is its output). Per output frame and channel:
 * 1 centre multiply + HB_K pair adds + HB_K multiplies = 26 mults, 50 adds (symmetric pairs, zero taps skipped), no division or modulo (linear double-written history). */
#define TAPS PC_DEC2_TAPS
#define CTR  ((TAPS - 1) / 2)
_Static_assert(PC_DEC2_TAPS % 4 == 1, "halfband form needs 4k+1 taps");

/* generated by tools/gen/gen_halfband.py 49: 101 taps, Kaiser beta 8.9, ripple 0.02892 dB, stopband 92.24 dB at 96 kHz.
 * HB_G[k] = h[centre + (2k+1)] (symmetric), centre tap HB_C; every other tap is zero. Unity DC gain. */
#define HB_K 25
static const float HB_C = 0.499997321f;
static const float HB_G[HB_K] = {
    0.317774839f, -0.104512199f, 0.0610420829f, -0.0418698562f,
    0.0308435717f, -0.0235677385f, 0.0183578447f, -0.014431043f,
    0.0113739181f, -0.00894642775f, 0.0069979885f, -0.00542751253f,
    0.00416283337f, -0.00314949811f, 0.00234441814f, -0.00171218244f,
    0.00122288947f, -0.000850866245f, 0.00057390887f, -0.000372824262f,
    0.00023113729f, -0.000134878945f, 7.24042043e-05f, -3.42102796e-05f,
    1.27409133e-05f,
};
_Static_assert(HB_K == (PC_DEC2_TAPS - 1) / 4, "HB table length does not match PC_DEC2_TAPS: regenerate with tools/gen/gen_halfband.py");
_Static_assert(sizeof HB_G / sizeof HB_G[0] == HB_K, "HB_G initializer length");

/* History per channel: 2 * TAPS floats, every input written at hpos and hpos + TAPS, so h + hpos is always the TAPS most recent
 * inputs in order (oldest first) as one contiguous window: tap i is w[i]. */
struct pc_dec2 {
    float hist[2][2 * TAPS];
    int   hpos, phase;
};

size_t pc_dec2_size(void) { return (sizeof(struct pc_dec2) + 7) & ~(size_t)7; }

void pc_dec2_init(pc_dec2_t *d) { memset(d, 0, sizeof *d); }

static float hb_dot(const float *w)
{
    float acc = HB_C * w[CTR];
    for (int k = 0; k < HB_K; k++) acc += HB_G[k] * (w[CTR - 2 * k - 1] + w[CTR + 2 * k + 1]);
    return acc;
}

int pc_dec2_run(pc_dec2_t *d, const float *in, int in_frames, float *out)
{
    int done = 0;
    for (int k = 0; k < in_frames; k++) {
        float l = in[2 * (size_t)k], r = in[2 * (size_t)k + 1];   /* read before the output (maybe the same buffer) is written */
        d->hist[0][d->hpos] = d->hist[0][d->hpos + TAPS] = l;
        d->hist[1][d->hpos] = d->hist[1][d->hpos + TAPS] = r;
        d->hpos = d->hpos + 1 == TAPS ? 0 : d->hpos + 1;
        if (++d->phase < 2) continue;
        d->phase = 0;
        float a = hb_dot(d->hist[0] + d->hpos), b = hb_dot(d->hist[1] + d->hpos);
        out[2 * (size_t)done] = a;
        out[2 * (size_t)done + 1] = b;
        done++;
    }
    return done;
}

/* x2 interpolator. Zero-stuffed input z[2n] = x[n], z[2n+1] = 0 through the same filter times 2: the even output is
 * 2 * HB_C * x (a pure delay of CTR / 2 inputs, 2 * HB_C ~ 1), the odd output is 2 * sum of the odd taps over x[n - t],
 * t = 0 .. CTR - 1 (pair t = CTR/2 - 1 - k and CTR/2 + k with HB_G[k]). Per input frame and channel: 26 mults, 49 adds, no modulo.
 * History: CTR inputs per channel, double-written; the window w (oldest first, w[CTR-1-t] = x[n-t]) is contiguous. */
struct pc_int2 {
    float hist[2][2 * CTR];
    int   hpos;
};

size_t pc_int2_size(void) { return (sizeof(struct pc_int2) + 7) & ~(size_t)7; }

void pc_int2_init(pc_int2_t *s) { memset(s, 0, sizeof *s); }

static void int_frame(const float *w, float *even, float *odd)
{
    *even = 2 * HB_C * w[CTR - 1 - CTR / 2];
    float acc = 0;
    for (int k = 0; k < HB_K; k++) acc += HB_G[k] * (w[CTR / 2 + k] + w[CTR / 2 - 1 - k]);
    *odd = 2 * acc;
}

int pc_int2_run(pc_int2_t *s, const float *in, int in_frames, float *out)
{
    for (int k = 0; k < in_frames; k++) {
        s->hist[0][s->hpos] = s->hist[0][s->hpos + CTR] = in[2 * (size_t)k];
        s->hist[1][s->hpos] = s->hist[1][s->hpos + CTR] = in[2 * (size_t)k + 1];
        int w0 = s->hpos + 1 == CTR ? 0 : s->hpos + 1;           /* oldest sample of the window */
        float e0, o0, e1, o1;
        int_frame(s->hist[0] + w0, &e0, &o0);
        int_frame(s->hist[1] + w0, &e1, &o1);
        out[4 * (size_t)k] = e0;
        out[4 * (size_t)k + 1] = e1;
        out[4 * (size_t)k + 2] = o0;
        out[4 * (size_t)k + 3] = o1;
        s->hpos = w0;
    }
    return 2 * in_frames;
}
