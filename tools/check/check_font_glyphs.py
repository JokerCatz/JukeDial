"""Every non-ASCII character in a string literal of app/main/**/*.c (and *.def: the sound bank sfx_bank.def) and components/player_core/src (the fx apps pc_fxapp*.c: their row names and descriptions are on screen) must have a glyph in the UI font files (fonts/ui-tc.ttf ui-sc.ttf ui-ext.ttf).

The font files are generated by make_font_subset.py from the characters of app/main, so a new character in a label is missing on the board
until the fonts are regenerated, copied to the card and flashed (make flash-fonts). This check finds that at lint time.
tools/check/font_glyphs_known_missing.txt lists characters known to be missing until the fonts are regenerated (one per line, "# reason" after it);
they do not fail the check, and the check says when one of them has a glyph again (remove the line).
usage: check_font_glyphs.py [fonts_dir [known_missing_file]]   (known_missing_file: default tools/check/font_glyphs_known_missing.txt; /dev/null = none allowed)
(fonts_dir default: fonts/ next to tools/; no fonts there = skipped, exit 0; missing glyphs = exit 1)
Standard library only (reads the cmap tables, formats 4 and 12)."""
import os, re, struct, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "gen"))   # tools/gen: sibling tools live in other folders

def cmap_chars(path):
    d = open(path, 'rb').read()
    ntab = struct.unpack('>H', d[4:6])[0]
    off = next((struct.unpack('>I', d[12 + 16 * i + 8:12 + 16 * i + 12])[0] for i in range(ntab) if d[12 + 16 * i:12 + 16 * i + 4] == b'cmap'), None)
    if off is None:
        raise SystemExit(f'{path}: no cmap table')
    chars = set()
    for i in range(struct.unpack('>H', d[off + 2:off + 4])[0]):
        pid, eid, so = struct.unpack('>HHI', d[off + 4 + 8 * i:off + 12 + 8 * i])
        s = off + so
        fmt = struct.unpack('>H', d[s:s + 2])[0]
        if fmt == 12:
            for g in range(struct.unpack('>I', d[s + 12:s + 16])[0]):
                a, b, gid = struct.unpack('>III', d[s + 16 + 12 * g:s + 28 + 12 * g])
                if gid:
                    chars.update(range(a, b + 1))
        elif fmt == 4:
            n = struct.unpack('>H', d[s + 6:s + 8])[0] // 2
            end = struct.unpack('>%dH' % n, d[s + 14:s + 14 + 2 * n])
            st = struct.unpack('>%dH' % n, d[s + 16 + 2 * n:s + 16 + 4 * n])
            for a, b in zip(st, end):
                if a != 0xFFFF:
                    chars.update(range(a, b + 1))
    return chars

LIT = re.compile(r'"((?:[^"\\\n]|\\.)*)"')

def literal_chars(root, repo):
    found = {}
    for dp, _, fns in os.walk(root):
        for fn in sorted(fns):
            if not fn.endswith(('.c', '.def')) or 'third_party' in dp:   # .def: the sound bank's text (app/main/sfx_bank.def), its labels are on screen
                continue
            p = os.path.join(dp, fn)
            for ln, line in enumerate(open(p, encoding='utf-8', errors='ignore'), 1):
                for m in LIT.finditer(line):
                    for c in m.group(1):
                        if ord(c) > 0x7f and c.isprintable():
                            found.setdefault(c, f'{os.path.relpath(p, repo)}:{ln}')
    return found

def main():
    here = os.path.dirname(os.path.abspath(__file__))
    fdir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', '..', 'fonts')
    files = [os.path.join(fdir, n) for n in ('ui-tc.ttf', 'ui-sc.ttf', 'ui-ext.ttf')]
    if not all(os.path.isfile(f) for f in files):
        print('check_font_glyphs: skipped (no fonts/ui*.ttf here)')
        return 0
    have = set()
    for f in files:
        have |= cmap_chars(f)
    found = {}
    repo = os.path.abspath(os.path.join(here, '..', '..'))
    for sub in (('app', 'main'), ('components', 'player_core', 'src'), ('components', 'player_core', 'include')):
        for c, w in literal_chars(os.path.join(repo, *sub), repo).items():
            found.setdefault(c, w)
    sys.path.insert(0, here)
    try:
        import gen_card_themes as G                  # the shipped card themes' display names (name_tc / name_sc): not C literals, but on the 配色 row
    except ImportError:                              # a copy of this script alone (sim/test.sh): nothing to add
        G = None
    for n, t in (G.THEMES.items() if G else ()):
        for c in t[0] + t[1]:
            if ord(c) > 0x7f and c.isprintable():
                found.setdefault(c, f'tools/gen/gen_card_themes.py (theme {n})')
    known = set()
    kp = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, 'font_glyphs_known_missing.txt')
    if os.path.isfile(kp):
        known = {l[0] for l in open(kp, encoding='utf-8') if l.strip() and not l.startswith('#')}
    for c in sorted(known):
        if ord(c) in have:
            print(f'check_font_glyphs: {c} is in the fonts now: remove it from font_glyphs_known_missing.txt')
    missing = {c: w for c, w in found.items() if ord(c) not in have and c not in known}
    for c, w in sorted(missing.items(), key=lambda x: x[1]):
        print(f'check_font_glyphs: U+{ord(c):04X} {c} has no glyph in fonts/ui*.ttf (first used at {w})')
    print(f'check_font_glyphs: {len(found)} characters in string literals, {len(missing)} without a glyph (+{len(known & set(found))} known)')
    return 1 if missing else 0

if __name__ == '__main__':
    sys.exit(main())
