"""Icons as text (ICON-A). Reads app/main/ui/icons.def (ICON(ID, FAMILY, "source name", 0xCODE, "purpose")).

  make_icons.py --header            write app/main/ui/icons_gen.h (UI_ICON_<ID> UTF-8 string macros); needs no sources
  make_icons.py --check-header      exit 1 when icons_gen.h is not what icons.def says (lint-app runs this through tools/check/check_icons.py)
  make_icons.py --fetch DIR         download the pinned upstream npm packages into DIR (checked against the pinned SHA-256, extracted with tarfile's "data" filter, never executed)
  make_icons.py --sheet OUTDIR --font-file ui-icon.ttf --text-font ui-tc.ttf    the owner's icon maps (Pillow): icon_map_filled.png, icon_map_line.png (every CHOSEN icon of the family, actual pixel
                                    size normal + selected, and 3x enlarged, with its id and its name in zh-TW) and icon_menu_map.png (each menu item's name next to its icon, round and square size).
                                    With --lang cn|en: only the menu map in that language (icon_menu_map_<lang>.png; names in tools/gen/icon_names_l10n.tsv).
                                    Only the icons of icons.def; nothing of the full upstream sets.
  make_icons.py --font OUT.ttf --src DIR    build the icon font: the glyphs of the pinned Tabler Icons (MIT, LINE) and Material Symbols Rounded (Apache-2.0, FILLED at
                                    FILL 1, weight 400, optical size 24) as outlines at their private-use code points, scaled so a 24-unit icon box is 0.86 em and
                                    centred on the text's x-height middle. Needs fontTools (+ brotli for the woff2): FONT_PY=<python with them>.
The font is vector: FreeType draws it at every text size (20, 28 px and the menu icon size) from the one file, so no per-size bitmap is stored.
The font file (fonts/ui-icon.ttf) is not in git (like the other fonts); this tool, icons.def and icons_gen.h are."""
import hashlib, os, re, sys, tarfile, urllib.request
os.environ.setdefault("SOURCE_DATE_EPOCH", "1700000000")   # fontTools stamps head.modified with it: same inputs, same bytes (make fonts-check)

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEF = os.path.join(ROOT, "app/main/ui/icons.def")
HDR = os.path.join(ROOT, "app/main/ui/icons_gen.h")
# pinned upstream (checked 2026-11-17): version, tarball, SHA-256 of the tarball, file inside it
PINS = {
    "tabler": ("@tabler/icons-webfont 3.52.0 (MIT)", "https://registry.npmjs.org/@tabler/icons-webfont/-/icons-webfont-3.52.0.tgz",
               "44d285b2f266b807cc864e2d4a831552fa8e6b1b3af38dd407501ea58dfb13ee", "package/dist/fonts/tabler-icons.ttf"),
    "msym": ("material-symbols 0.49.0 (Apache-2.0)", "https://registry.npmjs.org/material-symbols/-/material-symbols-0.49.0.tgz",
             "ca62c2e360fbee53341610eb1d97c783c96480cb03aa135ba2ab67c290a473e4", "package/material-symbols-rounded.woff2"),
}
EM = 1000
BOX = 860           # a 24-unit icon box in font units (0.86 em)
MID = 360           # its vertical middle above the baseline (the x-height middle of the text fonts)


def parse():
    icons = []
    for ln in open(DEF, encoding="utf-8"):
        m = re.match(r'ICON\((\w+),\s*(FILLED|LINE),\s*"([^"]+)",\s*(0x[0-9A-Fa-f]+),\s*"([^"]*)"\)', ln)
        if m:
            icons.append((m[1], m[2], m[3], int(m[4], 16), m[5]))
        elif ln.startswith("ICON("):
            sys.exit(f"icons.def: cannot parse: {ln.strip()}")
    return icons


def header_text(icons):
    out = ["// SPDX-License-Identifier: LGPL-2.1-or-later", "/* GENERATED by tools/gen/make_icons.py --header from icons.def: do not edit. Each macro is the icon's code point as UTF-8 (a string literal): \"x\" UI_ICON_HOME \" y\". */",
           "#pragma once"]
    for i, fam, src, cp, why in icons:
        u = chr(cp).encode("utf-8")
        out.append(f'#define UI_ICON_{i:<12} "{"".join(f"\\{b:03o}" for b in u)}"   /* U+{cp:04X} {fam} {src}: {why} */')
    return "\n".join(out) + "\n"


def fetch(d):
    os.makedirs(d, exist_ok=True)
    for k, (what, url, sha, member) in PINS.items():
        tgz = os.path.join(d, k + ".tgz")
        if not os.path.exists(tgz):
            print("fetch", what)
            urllib.request.urlretrieve(url, tgz)
        got = hashlib.sha256(open(tgz, "rb").read()).hexdigest()
        if got != sha:
            sys.exit(f"{tgz}: SHA-256 {got} is not the pinned {sha}")
        with tarfile.open(tgz) as t:
            ext = os.path.join(d, k)
            os.makedirs(ext, exist_ok=True)
            t.extract(member, ext, filter="data")
            lic = [n for n in t.getnames() if n.endswith("/LICENSE")]
            for n in lic:
                t.extract(n, ext, filter="data")
        print("ok", what)


def build_font(out, src):
    from fontTools.fontBuilder import FontBuilder
    from fontTools.pens.transformPen import TransformPen
    from fontTools.pens.ttGlyphPen import TTGlyphPen
    from fontTools.pens.cu2quPen import Cu2QuPen
    from fontTools.ttLib import TTFont
    from fontTools.varLib import instancer
    icons = parse()
    tab = TTFont(os.path.join(src, "tabler", PINS["tabler"][3]))
    ms = instancer.instantiateVariableFont(TTFont(os.path.join(src, "msym", PINS["msym"][3])), {"FILL": 1, "wght": 400, "opsz": 24, "GRAD": 0})
    face = {"LINE": (tab, tab.getGlyphSet(), 500.0, 400.0, BOX / 834.0), "FILLED": (ms, ms.getGlyphSet(), 480.0, 480.0, BOX / 960.0)}
    # Tabler: 24-unit box = x 83..917, y -17..817 (centre 500, 400) of 1000; Material: 0..960 both ways (centre 480, 480)
    order, glyphs, cmap, hmtx = [".notdef"], {}, {}, {".notdef": (EM, 0)}
    pen = TTGlyphPen(None)
    glyphs[".notdef"] = pen.glyph()
    for i, fam, name, cp, why in icons:
        f, gs, cx, cy, s = face[fam]
        if name.startswith("custom:"):          # our own drawing (tools/gen/icons_custom/<name>.svg, 24-unit grid, y down): same box and centre as the Material glyphs
            from fontTools.svgLib.path import parse_path
            from fontTools.pens.reverseContourPen import ReverseContourPen
            import xml.etree.ElementTree as ET
            k = BOX / 24.0
            p = TTGlyphPen(None)
            for el in ET.parse(os.path.join(ROOT, "tools/gen/icons_custom", name[7:] + ".svg")).iter("{http://www.w3.org/2000/svg}path"):
                parse_path(el.get("d"), TransformPen(ReverseContourPen(Cu2QuPen(p, 1.0, reverse_direction=False)), (k, 0, 0, -k, 500 - 12 * k, MID + 12 * k)))
            gn = "i_" + i.lower()
            order.append(gn); glyphs[gn] = p.glyph(); cmap[cp] = gn; hmtx[gn] = (EM, 0)
            continue
        if name not in gs:
            sys.exit(f"icons.def: {i}: no glyph '{name}' in the {fam} source")
        p = TTGlyphPen(None)
        gs[name].draw(Cu2QuPen(TransformPen(p, (s, 0, 0, s, 500 - cx * s, MID - cy * s)), 1.0, reverse_direction=False))
        gn = "i_" + i.lower()
        order.append(gn)
        glyphs[gn] = p.glyph()
        cmap[cp] = gn
        hmtx[gn] = (EM, 0)
    fb = FontBuilder(EM, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    glyf = fb.font["glyf"]
    for k in hmtx: glyf[k].recalcBounds(glyf)
    # lsb = the glyph's xMin: FreeType moves the outline so xMin lands on the lsb, so lsb 0 drew every icon flush left (7 px off at 44 px)
    fb.setupHorizontalMetrics({k: (a, getattr(glyf[k], "xMin", 0)) for k, (a, _) in hmtx.items()})
    fb.setupHorizontalHeader(ascent=900, descent=-100)
    fb.setupNameTable({"familyName": "JC UI Icons", "styleName": "Regular"})
    fb.setupOS2(sTypoAscender=900, sTypoDescender=-100, usWinAscent=900, usWinDescent=100)
    fb.setupPost(keepGlyphNames=False)
    fb.save(out)
    print(f"icon font {out}: {len(icons)} icons, {os.path.getsize(out)} bytes")
    # coordinates are rounded to integers on save; recompute each bounding box from the saved glyphs
    t = TTFont(out)
    t.save(out)


COL = {"bg": (0, 4, 16), "cell": (24, 20, 65), "sel": (14, 106, 148), "fg": (230, 234, 255), "dim": (140, 150, 190)}


GROUPS = {"主選單": ("主选单", "Main menu"), "小工具": ("小工具", "Tools"), "遊戲": ("游戏", "Games"), "時鐘選單": ("时钟菜单", "Clock menu"),
          "藍牙選單": ("蓝牙菜单", "Bluetooth menu"), "占卜選單": ("占卜菜单", "Fortune menu"), "所有選單": ("所有菜单", "Every menu"), "播放頁": ("播放页", "Now playing")}
HEAD = {"tw": "menu mapping: name | round cell (44 px) | square cell (40 px, icon above the name)",
        "cn": "菜单对应：名称 | 圆屏格（44 px）| 方屏格（40 px，图标在名称上方）",
        "en": "Menu mapping: name | round cell (44 px) | square cell (40 px, icon above the name)"}


def sheet(outdir, iconfont, textfont, lang="tw"):
    """lang tw (default): all the sheets, names from icon_names_zh.txt; cn / en: only the menu map, names from icon_names_l10n.tsv, written to icon_menu_map_<lang>.png"""
    from PIL import Image, ImageDraw, ImageFont
    icons = parse()
    zh = dict(l.rstrip("\n").split("\t", 1) for l in open(os.path.join(ROOT, "tools/gen/icon_names_zh.txt"), encoding="utf-8") if l.strip() and not l.startswith("#"))
    icons = [(i, f, s, c, zh.get(i, w)) for i, f, s, c, w in icons]
    if lang != "tw":
        col = {"cn": 1, "en": 2}[lang]
        nm = {l.split("\t")[0]: l.rstrip("\n").split("\t")[col] for l in open(os.path.join(ROOT, "tools/gen/icon_names_l10n.tsv"), encoding="utf-8") if l.strip() and not l.startswith("#")}
        icons = [(i, f, s, c, GROUPS[w.partition("：")[0]][col - 1] + "：" + nm[i]) for i, f, s, c, w in icons if f == "FILLED"]
    os.makedirs(outdir, exist_ok=True)
    idx = 0
    if textfont.endswith(".ttc"): idx = 2 if lang == "cn" else 3   # Noto CJK collection: 2 = SC, 3 = TC
    tf = ImageFont.truetype(textfont, 15, index=idx)
    tf_s = ImageFont.truetype(textfont, 13, index=idx)

    def glyph(cp, px, bg, fg):          # the glyph exactly as FreeType renders it at px (A8 coverage), composited on bg in the text colour
        f = ImageFont.truetype(iconfont, px, layout_engine=ImageFont.Layout.BASIC)
        a = Image.new("L", (px + 8, px + 8), 0)
        ImageDraw.Draw(a).text((4, 4 + px * 0.0), chr(cp), font=f, fill=255, anchor="la")
        im = Image.new("RGB", a.size, bg)
        im.paste(Image.new("RGB", a.size, fg), mask=a)
        return im

    def paste3(img, im, x, y):
        img.paste(im.resize((im.width * 3, im.height * 3), Image.NEAREST), (x, y))

    for fam, name, sizes in ((("FILLED", "icon_map_filled.png", (44, 40)), ("LINE", "icon_map_line.png", (20, 28))) if lang == "tw" else ()):
        cs = [i for i in icons if i[1] == fam]
        cols, cw = 4, 330
        ch = 26 + sizes[0] + 3 * (sizes[0] + 8) + 62
        img = Image.new("RGB", (cols * cw, 40 + ((len(cs) + cols - 1) // cols) * ch), COL["bg"])
        d = ImageDraw.Draw(img)
        d.text((10, 10), f"{fam}: every chosen icon, actual size (px {sizes[0]} / {sizes[1]}: normal, selected) and 3x enlarged", font=tf, fill=COL["fg"])
        for n, (i, _, src, cp, why) in enumerate(cs):
            x0, y0 = (n % cols) * cw, 40 + (n // cols) * ch
            d.rectangle((x0 + 4, y0 + 4, x0 + cw - 4, y0 + ch - 4), fill=COL["cell"])
            x = x0 + 12
            for px in sizes:
                for bg in (COL["cell"], COL["sel"]):
                    im = glyph(cp, px, bg, COL["fg"])
                    img.paste(im, (x, y0 + 12))
                    x += im.width + 2
            paste3(img, glyph(cp, sizes[0], COL["cell"], COL["fg"]), x0 + 12, y0 + 18 + sizes[0] + 8)
            d.text((x0 + 12, y0 + ch - 50), f"{i}  U+{cp:04X}", font=tf, fill=COL["fg"])
            d.text((x0 + 12, y0 + ch - 30), why, font=tf_s, fill=COL["dim"])
        img.save(os.path.join(outdir, name))
    groups = {}
    for i, fam, src, cp, why in icons:
        if fam == "FILLED":
            g, _, item = why.partition("：")
            groups.setdefault(g, []).append((item, cp))
    rows = sum((len(v) + 1) // 2 for v in groups.values()) + len(groups)
    img = Image.new("RGB", (900, 50 + rows * 66), COL["bg"])
    d = ImageDraw.Draw(img)
    d.text((10, 10), HEAD[lang], font=tf, fill=COL["fg"])
    y = 40
    for g, items in groups.items():
        d.text((10, y), g, font=tf, fill=COL["dim"])
        y += 28
        for k in range(0, len(items), 2):
            for c, (item, cp) in enumerate(items[k:k + 2]):
                x = 10 + c * 440
                d.text((x, y + 18), item, font=tf, fill=COL["fg"])
                d.rectangle((x + 190, y, x + 250, y + 56), fill=COL["cell"])
                img.paste(glyph(cp, 44, COL["cell"], COL["fg"]).crop((0, 0, 52, 52)), (x + 194, y + 2))
                d.rectangle((x + 260, y, x + 420, y + 60), fill=COL["cell"])
                im = glyph(cp, 40, COL["cell"], COL["fg"])
                img.paste(im.crop((0, 0, 48, 48)), (x + 316, y + 0))
                d.text((x + 340 - d.textlength(item, font=tf_s) / 2, y + 44), item, font=tf_s, fill=COL["fg"])
            y += 66
    img = img.crop((0, 0, 900, y + 10))
    img.save(os.path.join(outdir, "icon_menu_map.png" if lang == "tw" else f"icon_menu_map_{lang}.png"))


def main(a):
    if "--header" in a:
        open(HDR, "w", encoding="utf-8").write(header_text(parse()))
    elif "--check-header" in a:
        if not os.path.exists(HDR) or open(HDR, encoding="utf-8").read() != header_text(parse()):
            sys.exit("icons_gen.h is not what icons.def says: run `make icons-header`")
    elif "--sheet" in a:
        sheet(a[a.index("--sheet") + 1], a[a.index("--font-file") + 1], a[a.index("--text-font") + 1], a[a.index("--lang") + 1] if "--lang" in a else "tw")
    elif "--fetch" in a:
        fetch(a[a.index("--fetch") + 1])
    elif "--font" in a:
        build_font(a[a.index("--font") + 1], a[a.index("--src") + 1])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    if sys.argv[1:2] in (["-h"], ["--help"]):          # usage only: before any side effect
        print(__doc__); sys.exit(0)
    main(sys.argv[1:])
