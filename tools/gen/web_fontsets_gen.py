"""tools/web/fontsets.js: the character sets of `make fonts-build` (tools/gen/make_font_subset.py) as page data, so the browser builds the same fonts.
One source: this script imports make_font_subset.py's own functions (big5_level1, gb2312, listed_chars) and walks the same source trees; nothing is copied by hand.
  web_fontsets_gen.py           write tools/web/fontsets.js
  web_fontsets_gen.py --check   fail when the file is not what the sources give (webcheck runs it; run the writer after changing app strings or tools/gen/font_sets/)
Needs no fontTools (make_font_subset.py is read as text up to its fontTools import and only its pure functions are used)."""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'web', 'fontsets.js')
src = open(os.path.join(HERE, 'make_font_subset.py'), encoding='utf-8').read()
src = src.replace('from fontTools import subset\nfrom fontTools.ttLib import TTFont\n', '')
ns = {'__name__': 'mfs'}
exec(compile(src[:src.index('def main():')], 'make_font_subset', 'exec'), ns)

def sources():
    out = set()
    for sub in (('app', 'main'), ('components', 'player_core', 'src'), ('components', 'player_core', 'include')):
        for root, dirs, files in os.walk(os.path.join(HERE, '..', '..', *sub)):
            dirs.sort()
            for fn in sorted(files):
                if fn.endswith(('.c', '.h', '.def')):
                    out |= set(open(os.path.join(root, fn), encoding='utf-8', errors='ignore').read())
    return out

def s(chars): return ''.join(sorted((c for c in chars if c.isprintable()), key=ord))
def js(x): return '"' + x.replace('\\', '\\\\').replace('"', '\\"') + '"'

def render():
    base = set(chr(c) for c in range(0x20, 0x7f)) | set(chr(c) for c in range(0x3000, 0x3100)) | set(chr(c) for c in range(0xff00, 0xff70)) | set('…·—–‘’“”•°')
    b5 = ns['big5_level1'](); g1 = ns['gb2312'](False); g2 = ns['gb2312'](True) - g1
    lib = ns['listed_chars'](os.path.join(HERE, 'font_sets', 'library_chars.txt')); ext = ns['listed_chars'](os.path.join(HERE, 'font_sets', 'extra_chars.txt'))
    app = sources()
    L = ['// SPDX-License-Identifier: LGPL-2.1-or-later', '/* generated by tools/gen/web_fontsets_gen.py from tools/gen/make_font_subset.py\'s rules and tools/gen/font_sets/ -- do not edit by hand.',
         '   base: ASCII, kana and CJK punctuation, full-width forms, a few marks; big5: Big5 level 1; gb1 / gb2: GB2312 level 1 / level 2; library: tools/gen/font_sets/library_chars.txt;',
         '   extra: tools/gen/font_sets/extra_chars.txt; app: every character in app/main and player_core sources. The union is what `make fonts-build` wants. */',
         'const FONT_SETS = {']
    for k, v in (('base', base), ('big5', b5), ('gb1', g1), ('gb2', g2), ('library', lib), ('extra', ext), ('app', app)):
        L.append(f'  {k}: {js(s(v))},')
    L.append('};')
    return '\n'.join(L) + '\n'

if __name__ == '__main__':
    if sys.argv[1:2] in (["-h"], ["--help"]):          # usage only: before any side effect
        print(__doc__); sys.exit(0)
    t = render()
    if '--check' in sys.argv:
        if not os.path.isfile(OUT) or open(OUT, encoding='utf-8').read() != t: print('web_fontsets_gen: tools/web/fontsets.js is not the sources\' (run tools/gen/web_fontsets_gen.py)'); sys.exit(1)
        print('web_fontsets_gen: ok'); sys.exit(0)
    open(OUT, 'w', encoding='utf-8').write(t)
