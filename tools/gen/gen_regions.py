"""tools/gen/i18n/regions.tsv (the one neutral region table) -> tools/web/regions.js (const REGIONS, read by the radio search of tools/web/index.html).
usage: gen_regions.py [--check]   --check: exit 1 when regions.js is not the table's (also: duplicate codes, a code that is no two capital letters, a blank name, a rank that repeats)."""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
SRC, OUT = os.path.join(HERE, 'i18n', 'regions.tsv'), os.path.join(HERE, '..', 'web', 'regions.js')

def rows():
    out = []
    for l in open(SRC, encoding='utf-8').read().split('\n'):
        if not l or l.startswith('#'): continue
        f = l.split('\t'); f += [''] * (6 - len(f))
        out.append(f[:6])
    return out

def render(rs):
    s = ['// SPDX-License-Identifier: LGPL-2.1-or-later', '/* generated by tools/gen/gen_regions.py from tools/gen/i18n/regions.tsv -- do not edit by hand. code: [zh_tw, zh_cn, en, rank_tw, rank_cn] (rank 99: by station count) */', 'const REGIONS={']
    for c, tw, cn, en, rt, rc in rs:
        s.append(f'{c}:' + json.dumps([tw, cn, en, int(rt or 99), int(rc or 99)], ensure_ascii=False, separators=(',', ':')) + ',')
    s.append('};')
    return '\n'.join(s) + '\n'

def main():
    if sys.argv[1:2] in (["-h"], ["--help"]):          # usage only: before any side effect
        print(__doc__); sys.exit(0)
    rs = rows(); bad = 0
    seen = set()
    for r in rs:
        if not re.fullmatch(r'[A-Z]{2}', r[0]) or r[0] in seen: print('gen_regions: bad or duplicate code', r[0]); bad = 1
        seen.add(r[0])
        if not (r[1] and r[2] and r[3]): print('gen_regions: blank name', r[0]); bad = 1
    for k in (4, 5):
        v = [r[k] for r in rs if r[k]]
        if len(v) != len(set(v)): print('gen_regions: a rank repeats'); bad = 1
    text = render(rs)
    if '--check' in sys.argv:
        if not os.path.isfile(OUT) or open(OUT, encoding='utf-8').read() != text: print('gen_regions: tools/web/regions.js is not the table\'s (run tools/gen/gen_regions.py)'); bad = 1
        return bad
    if bad: return 1
    open(OUT, 'w', encoding='utf-8').write(text)
    return 0

if __name__ == '__main__': sys.exit(main())
