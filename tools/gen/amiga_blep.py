"""Generates components/libxmp/libxmp/src/precomp_blep_a1200.h: the Paula band-limited step table of the "A1200" tone.
libxmp 4.7.2 ships only the two A500 tables (fixed filter, fixed + LED filter); upstream removed the A1200 one. Ours is our own design, not libxmp's:
a plain windowed-sinc band limit (no analogue filter after Paula), the step residual 1 - integral(h) in 2048 clock ticks of 3.546895 MHz, scaled 131072
like the upstream tables. Blackman-Harris window over 2047 taps (centre delay 1023 ticks = 0.29 ms), cutoff 17 kHz (below the 22.05 kHz Nyquist of 44.1 kHz).
Run: python3 tools/gen/amiga_blep.py > components/libxmp/libxmp/src/precomp_blep_a1200.h"""
import math
N, FS, FC = 2048, 3546895.0, 17000.0
D = (N - 1) // 2
M = N - 1
h = []
for i in range(M):
    n = i - D
    x = 2 * FC / FS * n
    s = 1.0 if n == 0 else math.sin(math.pi * x) / (math.pi * x)
    u = i / (M - 1)
    w = 0.35875 - 0.48829 * math.cos(2 * math.pi * u) + 0.14128 * math.cos(4 * math.pi * u) - 0.01168 * math.cos(6 * math.pi * u)
    h.append(s * w)
tot = sum(h)
h = [v / tot for v in h]
out, acc = [], 0.0
for i in range(N):
    out.append(round((1.0 - acc) * 131072))           # residual before tap i is added: 131072 at age 0, 0 at the end
    acc += h[i] if i < M else 0.0
out[-1] = 0
print("/* Table generated by tools/gen/amiga_blep.py (JukeDial's own A1200 tone: windowed-sinc step residual, no analogue filter) */")
print("const int winsinc_integral_a1200[2048] = {")
for r in range(0, N, 16):
    print(",".join(str(v) for v in out[r:r + 16]) + ",")
print("};")
