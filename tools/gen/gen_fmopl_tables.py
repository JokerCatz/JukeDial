"""Generates components/libadplug/adplug/fmopl_tables.h: the fmopl 0.37a lookup tables that OPLOpenTable used to compute at every open with
double pow / sin / log10 (8200 soft-double libm calls, about 0.1-0.3 s per open on the S31, whose FPU is single precision only).
Same expressions, same evaluation order and the same C truncations as the original code (math.* is the C libm), so the values are the ones the
host build always had. `--check` regenerates and compares with the file (make lint-app)."""
import math, sys, os

EG_ENT, TL_BITS, SIN_ENT, AMS_ENT, VIB_ENT, VIB_RATE = 4096, 26, 2048, 512, 512, 256
EG_STEP = 96.0 / EG_ENT
PI = 3.14159265358979323846
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "components", "libadplug", "adplug", "fmopl_tables.h")


def arr(name, ctype, vals, per=16):
    rows = ["\t" + ",".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return "static const %s %s[%d] = {\n%s\n};\n" % (ctype, name, len(vals), ",\n".join(rows))


def build():
    tl = [int(((1 << TL_BITS) - 1) / math.pow(10, EG_STEP * t / 20)) for t in range(EG_ENT - 1)]
    sin_j = [0]
    for s in range(1, SIN_ENT // 4 + 1):
        pom = math.sin(2 * PI * s / SIN_ENT)
        pom = 20 * math.log10(1 / pom)
        sin_j.append(int(pom / EG_STEP))
    env = [int(math.pow((EG_ENT - 1 - i) / EG_ENT, 8) * EG_ENT) for i in range(EG_ENT)]
    ams1, ams2 = [], []
    for i in range(AMS_ENT):
        pom = (1.0 + math.sin(2 * PI * i / AMS_ENT)) / 2
        ams1.append(int((1.0 / EG_STEP) * pom))
        ams2.append(int((4.8 / EG_STEP) * pom))
    vib1, vib2 = [], []
    for i in range(VIB_ENT):
        pom = float(VIB_RATE) * 0.06 * math.sin(2 * PI * i / VIB_ENT)
        vib1.append(int(VIB_RATE + (pom * 0.07)))
        vib2.append(int(VIB_RATE + (pom * 0.14)))
    return tl, sin_j, env, ams1, ams2, vib1, vib2


def text():
    tl, sin_j, env, ams1, ams2, vib1, vib2 = build()
    h = "/* Generated by tools/gen/gen_fmopl_tables.py (do not edit): the values fmopl's OPLOpenTable computed with libm at every open. */\n"
    h += "#include <stdint.h>\n"
    h += arr("TL_BASE", "INT32", tl) + arr("SIN_J", "uint16_t", sin_j) + arr("ENV_ATTACK", "uint16_t", env)
    h += arr("AMS_1DB", "uint16_t", ams1) + arr("AMS_48DB", "uint16_t", ams2) + arr("VIB_7C", "uint16_t", vib1) + arr("VIB_14C", "uint16_t", vib2)
    return h


if __name__ == "__main__":
    if sys.argv[1:2] in (["-h"], ["--help"]):          # usage only: before any side effect
        print(__doc__); sys.exit(0)
    t = text()
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == t
        print("fmopl_tables.h", "ok" if ok else "OUT OF DATE (run tools/gen/gen_fmopl_tables.py)")
        sys.exit(0 if ok else 1)
    open(OUT, "w").write(t)
