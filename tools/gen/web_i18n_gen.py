"""The settings page's strings (tools/web/) in 繁中 / 简中 / English.

tools/gen/i18n/web_strings.tsv (id <TAB> zh_tw <TAB> zh_cn <TAB> en <TAB> status <TAB> ctx) is the one file people edit; the format is the device table's
(tools/gen/i18n/strings.tsv).  A row whose ctx is dev:S_X is the device's row S_X: the texts come from strings.tsv (one source for words both share);
the cells in the web file are only a copy that --check keeps equal.  {0} {1} are the arguments of T(id, a, b) in the page.

  web_i18n_gen.py            web_strings.tsv (+ strings.tsv for dev: rows) -> tools/web/i18n.js (WEB_STRINGS = {id: [zh_tw, zh_cn, en]}); syncs dev: cells
  web_i18n_gen.py --check    lint (webcheck, make lint-app, i18n_gen.py --check): i18n.js is the table's; every id used by the page exists, unused ids are reported;
                             the three texts take the same {n} and the same HTML tags; zh_cn has no Traditional characters; dev: copies equal the device rows;
                             no bare CJK in the page: a CJK string literal in a script, a CJK text node or placeholder/title attribute outside data-i* markup, or
                             static HTML whose fallback text is not the table's zh_tw.  Marked regions /* cjk-allow-begin */ ... /* cjk-allow-end */ are exempt (the
                             pretend-device demo data and its test asserts, the language names).
  web_i18n_gen.py --strict   also: no 'untranslated' rows (i18n_gen.py --strict runs this)
Standard library only."""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import i18n_gen as g

TSV = os.path.join(HERE, 'i18n', 'web_strings.tsv')
WEB = os.path.join(HERE, '..', 'web')
OUT = os.path.join(WEB, 'i18n.js')
FILES = ['index.html', 'lists.js', 'glyphpack.js', 'conn.js', 'lang.js', 'flasher.js', 'flashtab.js', 'fonttab.js', 'fontbuild.js', 'fontsubset.js', 'fontworker.js', 'fontput.js', 'page.js', 'pagemock.js', 'boot.js']
CJK = re.compile('[\u3000-\u9fff\uff00-\uffef]')
ARG = re.compile(r'\{(\d+)\}')
TAG = re.compile(r'</?\w+>')
HEAD = ['# Web page strings (tools/web/*): id <TAB> zh_tw <TAB> zh_cn <TAB> en <TAB> status <TAB> ctx.  Same columns as strings.tsv; {0} {1} are the arguments of T(id, a, b); \\n \\t \\\\ are escaped.',
        '# ctx dev:S_X = the device table row S_X is the text (all three columns come from tools/gen/i18n/strings.tsv; the cells here stay a copy that --check keeps equal).  Edit, then run python3 tools/gen/web_i18n_gen.py.']

def read_rows():
    rows = []
    for ln in open(TSV, encoding='utf-8'):
        if ln.startswith('#') or not ln.strip('\n'): continue
        f = ln.rstrip('\n').split('\t'); f += [''] * (6 - len(f))
        rows.append([f[0], g.unesc(f[1]), g.unesc(f[2]), g.unesc(f[3]), f[4], f[5]])
    return rows

def write_rows(rows):
    open(TSV, 'w', encoding='utf-8').write('\n'.join(HEAD + ['\t'.join((r[0], g.esc(r[1]), g.esc(r[2]), g.esc(r[3]), r[4], r[5])) for r in rows]) + '\n')

def resolve(rows):
    """dev: rows take the device row's texts; returns the problems"""
    dev = {r[0]: r for r in g.read_tsv()}; bad = []
    for r in rows:
        if r[5].startswith('dev:'):
            d = dev.get(r[5][4:])
            if not d: bad.append(f'{r[0]}: ctx {r[5]} is not a device id'); continue
            r[1:4] = [d[1], d[2], d[3]]
    return bad

def js_lit(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\t', '\\t').replace('\u2028', '\\u2028') + '"'

def render(rows):
    out = ['// SPDX-License-Identifier: LGPL-2.1-or-later\n/* generated by tools/gen/web_i18n_gen.py from tools/gen/i18n/web_strings.tsv (and the device rows it shares) -- do not edit by hand. id: [zh_tw, zh_cn, en] */', 'const WEB_STRINGS={']
    for r in sorted(rows):
        out.append(f'{r[0]}:[{js_lit(r[1])},{js_lit(r[2])},{js_lit(r[3])}],')
    out.append('};'); return '\n'.join(out) + '\n'

# ---- a small JS lexer: the string / template / regex literals outside comments
def lex(src):
    out = []; i = 0; n = len(src); prev = ''
    while i < n:
        c = src[i]
        if c == '/' and src[i+1:i+2] == '/':
            j = src.find('\n', i); i = n if j < 0 else j; continue
        if c == '/' and src[i+1:i+2] == '*':
            j = src.find('*/', i + 2); i = n if j < 0 else j + 2; continue
        if c in '\'"':
            j = i + 1
            while src[j] != c:
                j += 2 if src[j] == '\\' else 1
            out.append((c, i, src[i+1:j])); i = j + 1; prev = 'x'; continue
        if c == '`':
            j, parts = tmpl(src, i); out.append(('`', i, ''.join(p[1] for p in parts if p[0] == 's'))); out += [x for p in parts if p[0] == 'e' for x in lex(p[1])]; i = j; prev = 'x'; continue
        if c == '/' and (prev == '' or prev in '(,=:[!&|?{};+-*%<>~^'):
            j = i + 1; cls = False
            while True:
                d = src[j]
                if d == '\\': j += 2; continue
                if d == '[': cls = True
                elif d == ']': cls = False
                elif d == '/' and not cls: break
                j += 1
            out.append(('re', i, src[i:j+1])); i = j + 1; prev = 'x'; continue
        if not c.isspace(): prev = c
        i += 1
    return out

def tmpl(src, i):
    j = i + 1; parts = []; cur = ''
    while src[j] != '`':
        if src[j] == '\\': cur += src[j:j+2]; j += 2; continue
        if src[j] == '$' and src[j+1] == '{':
            if cur: parts.append(('s', cur)); cur = ''
            k = j + 2; d = 1
            while d:
                ch = src[k]
                if ch in '\'"':
                    q = ch; k += 1
                    while src[k] != q: k += 2 if src[k] == '\\' else 1
                elif ch == '`': k, _ = tmpl(src, k); continue
                elif ch == '{': d += 1
                elif ch == '}': d -= 1
                k += 1
            parts.append(('e', src[j+2:k-1])); j = k; continue
        cur += src[j]; j += 1
    if cur: parts.append(('s', cur))
    return j + 1, parts

def allowed(src):
    """character ranges between the cjk-allow markers"""
    r = []; i = 0
    while True:
        a = src.find('cjk-allow-begin', i)
        if a < 0: return r
        b = src.find('cjk-allow-end', a)
        r.append((a, len(src) if b < 0 else b)); i = len(src) if b < 0 else b

def scan_js(src, base, name, rows_by_id, used, probs):
    ok = allowed(src)
    for k, pos, txt in lex(src):
        if any(a <= pos < b for a, b in ok): continue
        if k in '\'"`':
            if CJK.search(txt): probs.append(f'{name}: bare CJK string literal {txt[:30]!r}')
        elif CJK.search(txt): probs.append(f'{name}: CJK in a regex literal {txt[:30]!r}')
    for m in re.finditer(r"\bT\(\s*'([^']*)'", src):
        if any(a <= m.start() < b for a, b in ok): continue
        used.add(m.group(1))
        if m.group(1) not in rows_by_id: probs.append(f'{name}: T({m.group(1)!r}) is not in web_strings.tsv')
    for m in ([] if name == 'lang.js' else re.finditer(r"\bT\((?!\s*')", src)):
        if not src.startswith('function T', m.start() - 9) and not any(a <= m.start() < b for a, b in ok):
            line = src[m.start():m.start()+40].split('\n')[0]
            if not re.match(r'T\(\)', line): probs.append(f'{name}: T( with something else than an id literal: {line!r}')

def scan_html(h, name, rows_by_id, used, probs):
    h = re.sub(r'<!--.*?-->', '', h, flags=re.S)
    h = re.sub(r'<(script|style)\b.*?</\1>', '', h, flags=re.S)
    def elem(m):   # an element carrying data-i / data-ih: its inner markup is the fallback text, which must be the table's zh_tw
        i = m.group(3); used.add(i)
        if i not in rows_by_id: probs.append(f'{name}: data-i="{i}" is not in web_strings.tsv')
        elif m.group(4) != rows_by_id[i][1]: probs.append(f'{name}: data-i {i}: the fallback text {m.group(4)[:30]!r} is not the table\'s zh_tw')
        return m.group(0)[:m.start(4) - m.start(0)] + m.group(0)[m.end(4) - m.start(0):]
    h = re.sub(r'<(\w+)([^>]*?\bdata-ih?="([^"]*)"[^>]*)>(.*?)</\1>', elem, h, flags=re.S)
    for t in re.findall(r'<[^>]*>', h):
        for am in re.finditer(r'\bdata-i-(\w+)="([^"]*)"', t):
            used.add(am.group(2))
            if am.group(2) not in rows_by_id: probs.append(f'{name}: data-i-{am.group(1)}="{am.group(2)}" is not in web_strings.tsv'); continue
            v = re.search(r'\b%s="([^"]*)"' % am.group(1), t)
            if v and v.group(1) != rows_by_id[am.group(2)][1]: probs.append(f'{name}: {am.group(1)} fallback {v.group(1)!r} is not the table\'s zh_tw')
        for am in re.finditer(r'\b(placeholder|title|alt|aria-label|value)="([^"]*)"', t):
            if CJK.search(am.group(2)) and not re.search(r'data-i-%s=' % am.group(1), t): probs.append(f'{name}: bare CJK attribute {am.group(1)}="{am.group(2)[:20]}"')
    for t in re.findall(r'(?<=>)[^<>]+(?=<)', h):
        if CJK.search(t): probs.append(f'{name}: bare CJK text {t.strip()[:30]!r}')

def sources():
    for fn in FILES:
        p = os.path.join(WEB, fn)
        if os.path.isfile(p): yield fn, open(p, encoding='utf-8').read()

def check(strict):
    rows = read_rows(); probs = resolve(rows)
    ids = {}
    for r in rows:
        if not re.fullmatch(r'W_[A-Z0-9_]+', r[0]): probs.append(f'{r[0]}: id must be W_UPPER_CASE')
        if r[0] in ids: probs.append(f'{r[0]}: duplicate id')
        ids[r[0]] = r
        a = [sorted(ARG.findall(x)) for x in r[1:4]]
        if not (a[0] == a[1] == a[2]): probs.append(f'{r[0]}: the three texts take different {{n}} arguments')
        t = [sorted(TAG.findall(x)) for x in r[1:4]]
        if not (t[0] == t[1] == t[2]): probs.append(f'{r[0]}: the three texts have different HTML tags')
        if not all(r[1:4]): probs.append(f'{r[0]}: an empty column')
        if any('\\\\' in x for x in r[1:4]): probs.append(f'{r[0]}: two backslashes in a row: a row written back with its escapes escaped again (edit rows only through read_rows/write_rows or --add)')
        if r[4] not in ('untranslated', 'translated', 'reviewed', 'same'): probs.append(f'{r[0]}: status {r[4]!r}')
        d = g.cn_defects(r[2])
        if d: probs.append(f'{r[0]}: zh_cn has Traditional characters or Taiwan wording: {" ".join(d)}')
        if strict and r[4] == 'untranslated': probs.append(f'{r[0]}: untranslated')
    # the dev: cells are a copy
    raw = {x[0]: x for x in read_rows()}
    for r in rows:
        if r[5].startswith('dev:') and raw[r[0]][1:4] != r[1:4]: probs.append(f'{r[0]}: the cells differ from the device row {r[5][4:]} (run tools/gen/web_i18n_gen.py)')
    used = set()
    for fn, src in sources():
        if fn.endswith('.html'):
            scan_html(src, fn, ids, used, probs)
            for m in re.finditer(r'<script>(.*?)</script>', src, flags=re.S): scan_js(m.group(1), 0, fn, ids, used, probs)
        else: scan_js(src, 0, fn, ids, used, probs)
    for u in sorted(set(ids) - used): print(f'web_i18n_gen: unused id {u}')
    if not os.path.isfile(OUT) or open(OUT, encoding='utf-8').read() != render(rows): probs.append('tools/web/i18n.js is not the table\'s (run tools/gen/web_i18n_gen.py)')
    for p in probs: print('web_i18n_gen:', p)
    print(f'web_i18n_gen: {len(rows)} ids, {sum(1 for r in rows if r[5].startswith("dev:"))} shared with the device, {sum(1 for r in rows if r[4] == "untranslated")} untranslated')
    return 1 if probs else 0

def add(argv):
    """--add ID ZH_TW ZH_CN EN: append a row the safe way (the file is read unescaped and written escaped once); real newlines / backslashes in the arguments are fine"""
    rows = read_rows()
    if any(r[0] == argv[0] for r in rows): print('web_i18n_gen: id exists'); return 1
    rows.append([argv[0], argv[1], argv[2], argv[3], 'translated', ''])
    write_rows(rows); open(OUT, 'w', encoding='utf-8').write(render(rows)); return 0

def main(argv=None):
    mode = (argv if argv is not None else sys.argv[1:])[:1]
    mode = mode[0] if mode else ''
    if mode in ('--check', '--strict'): return check(mode == '--strict')
    if mode == '--add': return add((argv if argv is not None else sys.argv[1:])[1:5])
    rows = read_rows(); bad = resolve(rows)
    for b in bad: print('web_i18n_gen:', b)
    if bad: return 1
    write_rows(rows); open(OUT, 'w', encoding='utf-8').write(render(rows)); return 0

if __name__ == '__main__':
    if sys.argv[1:2] in (["-h"], ["--help"]):          # usage only: before any side effect
        print(__doc__); sys.exit(0)
    sys.exit(main())
