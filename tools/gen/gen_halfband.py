"""Kaiser-windowed halfband FIR design for pc_dec2 / pc_int2 (stdlib only, deterministic).

usage: gen_halfband.py [taps] [--check]
  taps    start tap count (4k+1, default 49); raised in steps of 4 until the spec passes
  --check print only the design report (no C table)

Spec at 96 kHz in: passband ripple <= +-0.05 dB from 20 Hz to 20 kHz, stopband >= 90 dB from 28 kHz (to 48 kHz).
The passband edge is taken at 20 kHz of an 88.2 kHz input (0.2268 fs, the harder case: 44.1 kHz out must keep 20 kHz too).
Halfband form: h[C] = 0.5, h[C+-d] = 0 for even d, h[C+-d] = sinc-window for odd d; scaled to unity DC gain.
Beta is chosen per tap count by a scan (best worst-case stopband that keeps the passband in spec)."""
import math, sys

FS = 96000.0
PASS_HZ, STOP_HZ = 20000.0 * FS / 88200.0, 28000.0   # 20 kHz must also hold at 88.2 kHz in (44.1 kHz out): edge 0.2268 of the input rate
RIPPLE_DB, STOP_DB = 0.03, 90.0   # design limit 0.03 dB: margin inside the +-0.05 dB spec

def i0(x):
    s = t = 1.0
    k = 1
    while t > 1e-18 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s

def design(taps, beta):
    c = (taps - 1) // 2
    h = [0.0] * taps
    for n in range(taps):
        d = n - c
        if d == 0:
            s = 0.5
        elif d % 2 == 0:
            s = 0.0
        else:
            s = math.sin(math.pi * d / 2) / (math.pi * d)
        r = d / c
        w = i0(beta * math.sqrt(max(0.0, 1 - r * r))) / i0(beta)
        h[n] = s * w
    g = sum(h)
    return [v / g for v in h]

def resp_db(h, hz):
    w = 2 * math.pi * hz / FS
    c = (len(h) - 1) // 2
    re = h[c] + 2 * sum(h[c + d] * math.cos(w * d) for d in range(1, c + 1))   # symmetric: real
    return 20 * math.log10(max(abs(re), 1e-30))

def measure(h):
    rip = max(abs(resp_db(h, PASS_HZ * i / 400)) for i in range(1, 401))
    rip = max(rip, abs(resp_db(h, 20)))
    stop = -max(resp_db(h, STOP_HZ + (FS / 2 - STOP_HZ) * i / 800) for i in range(0, 801))
    return rip, stop

def best(taps):
    out = None
    for i in range(0, 161):
        beta = 4.0 + i * 0.1
        h = design(taps, beta)
        rip, stop = measure(h)
        if rip <= RIPPLE_DB and (out is None or stop > out[2]):
            out = (beta, h, stop, rip)
    return out

def main():
    if sys.argv[1:2] in (["-h"], ["--help"]):          # usage only: before any side effect
        print(__doc__); sys.exit(0)
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    taps = int(args[0]) if args else 49
    assert taps % 4 == 1
    while True:
        b = best(taps)
        if b:
            print("// taps %d  beta %.1f  ripple %.5f dB  stopband %.2f dB" % (taps, b[0], b[3], b[2]), file=sys.stderr)
        if b and b[2] >= STOP_DB + 0.5:
            break
        taps += 4
        if taps > 201:
            sys.exit("gen_halfband: spec not reachable up to 201 taps")
    beta, h, stop, rip = b
    c = (taps - 1) // 2
    nz = sum(1 for v in h if v != 0.0)
    print("design: taps %d (non-zero %d), beta %.1f, passband ripple %.5f dB (20 Hz..20 kHz), stopband %.2f dB (28 kHz..48 kHz)"
          % (taps, nz, beta, rip, stop), file=sys.stderr)
    if "--check" in sys.argv:
        return
    print("/* generated by tools/gen/gen_halfband.py %d: %d taps, Kaiser beta %.1f, ripple %.5f dB, stopband %.2f dB at 96 kHz.\n"
          " * HB_G[k] = h[centre + (2k+1)] (symmetric), centre tap HB_C; every other tap is zero. Unity DC gain. */" % (int(args[0]) if args else 49, taps, beta, rip, stop))
    print("#define PC_DEC2_TAPS %d" % taps)
    print("#define HB_K %d" % (c // 2))
    print("static const float HB_C = %.9gf;" % h[c])
    print("static const float HB_G[HB_K] = {")
    row = []
    for k in range(c // 2):
        row.append("%.9gf" % h[c + 2 * k + 1])
        if len(row) == 4 or k == c // 2 - 1:
            print("    " + ", ".join(row) + ",")
            row = []
    print("};")

main()
