"""Generate the simulator's LVGL config header from the firmware's app/sdkconfig.

usage: sim_lvconf.py SDKCONFIG OUT.h      write the header (only if its content changed, so make does not rebuild LVGL)
       sim_lvconf.py --check SDKCONFIG    print "KEY VALUE" for every generated define (for tests)
Only CONFIG_LV_* is taken: =y -> 1, numbers and strings as they are, "is not set" -> nothing.
A few keys are overridden for the host (OS none, SDL on); the last line of the header lists them."""
import os, re, sys

DROP = {"CONFIG_LV_OS_CUSTOM", "CONFIG_LV_OS_CUSTOM_INCLUDE", "CONFIG_LV_USE_OS"}
# CONFIG_LV_USE_OS is not written: lv_conf_kconfig.h derives it from CONFIG_LV_OS_NONE (a second define would be a redefinition).
SET = {
    "CONFIG_LV_OS_NONE": "1",
    "CONFIG_LV_DRAW_SW_DRAW_UNIT_CNT": "1",
    "CONFIG_LV_USE_SDL": "1",
    "CONFIG_LV_SDL_BUF_COUNT": "1",   # with kconfig present LVGL's own default would be 0
}

def generate(sdkconfig):
    out = {}
    with open(sdkconfig) as f:
        for line in f:
            m = re.match(r"(CONFIG_LV_\w+)=(.*)$", line.rstrip("\n"))
            if not m:
                continue
            k, v = m.groups()
            if k in DROP:
                continue
            if v == "y":
                v = "1"
            elif v == "n":
                continue
            out[k] = v
    out.update(SET)
    return out

def render(d):
    lines = ["/* generated by tools/simtools/sim_lvconf.py from app/sdkconfig; do not edit */",
             "#pragma once"]
    lines += ["#define %s %s" % (k, d[k]) for k in sorted(d)]
    lines.append("/* host overrides: dropped %s; set %s */" % (", ".join(sorted(DROP)), ", ".join("%s=%s" % kv for kv in SET.items())))
    return "\n".join(lines) + "\n"

def main(argv):
    check = "--check" in argv
    args = [a for a in argv if a != "--check"]
    if not args or (not check and len(args) != 2):
        print(__doc__, file=sys.stderr)
        return 2
    if not os.path.exists(args[0]):
        print("sim_lvconf: %s not found (run make build once first)" % args[0], file=sys.stderr)
        return 1
    d = generate(args[0])
    if check:
        for k in sorted(d):
            print(k, d[k])
        return 0
    text = render(d)
    try:
        if open(args[1]).read() == text:
            return 0
    except OSError:
        pass
    os.makedirs(os.path.dirname(os.path.abspath(args[1])), exist_ok=True)
    with open(args[1], "w") as f:
        f.write(text)
    return 0

if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
