#!/usr/bin/env python3
"""SPDX licence headers on our own source files.

  spdx_headers.py            add `SPDX-License-Identifier: LGPL-2.1-or-later` as the first line of every own source file that lacks one
  spdx_headers.py --check    fail (exit 1) listing the files that lack it; writes nothing (make lint-app, make spdx-check)
  spdx_headers.py --report   print the counts by category and the skipped files

Idempotent: a file whose first lines already carry an SPDX line is left alone.  The line goes after a shebang and after a first-line
encoding / vim comment; HTML after the doctype.  Comment style by language: C / C++ / H / JS `//`, CSS `/* */`, HTML `<!-- -->`, everything else `#`.
Not touched: vendored trees (the project rules list), copies of upstream examples (tools/bt_peer), spikes, docs, .superpowers, data and binary files, and files with their
own copyright / licence notice in the first lines (reported).  Generated files (banner "generated by tools/...") are never edited here: their GENERATOR writes the
line, and --check fails when it does not.  Pure Python; files come from `git ls-files` (a tree without git: os.walk)."""
import os, re, subprocess, sys

if sys.argv[1:2] in (["-h"], ["--help"]):          # usage only: before any side effect
    print(__doc__); sys.exit(0)

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
SPDX = "SPDX-License-Identifier: LGPL-2.1-or-later"

VENDORED = ["components/emu2413/", "components/gme/", "components/libadplug/", "components/libcrsid/", "components/libfreeaptx/", "components/libhvl/",
            "components/libldac/", "components/libmpcdec/", "components/libtta/", "components/libxmp/", "components/player_core/third_party/",
            "app/main/third_party/", "app/components/esp_tinyusb/", "tools/web/vendor/", "tools/fatfs_exfat/"]
OTHER_SKIP = ["tools/bt_peer/",      # copies of ESP-IDF examples (their own SPDX: Unlicense OR CC0-1.0)
              "spikes/", ".superpowers/", "docs/", ".worktrees/", "backup/", "components/player_core/build-host/"]
# own trees that get headers (everything else is not ours or not source)
OWN = ["app/main/", "app/CMakeLists.txt", "components/fakepod_bsp/", "components/jc3636f118_bsp/", "components/player_core/", "tools/", "sim/", "hwtest/", "Makefile",
       "CMakeLists.txt"]
SLASH = (".c", ".h", ".cpp", ".hpp", ".js", ".mjs")
HASH = (".py", ".sh", ".cmake", ".mk")
GEN_BANNER = re.compile(r"^\s*(/\*|//|#|<!--)?\s*generated by `?tools/", re.I)      # the first line: a banner naming an in-repo generator
OWN_NOTICE = re.compile(r"^\s*(//|#|/?\*)+\s*(copyright|SPDX-|licensed under|permission is hereby)", re.I | re.M)      # a real notice line in a comment, not the word in prose

def listing():
    try:
        out = subprocess.run(["git", "-C", ROOT, "ls-files", "-z"], capture_output=True, check=True).stdout.decode()
        return [p for p in out.split("\0") if p]
    except Exception:
        r = []
        for d, ds, fs in os.walk(ROOT):
            ds[:] = [x for x in ds if x not in (".git", "build", "node_modules")]
            r += [os.path.relpath(os.path.join(d, f), ROOT) for f in fs]
        return r

def style(path):
    b = os.path.basename(path)
    if b in ("Makefile", "CMakeLists.txt"): return "#"
    e = os.path.splitext(b)[1]
    if e in SLASH: return "//" if not (path.startswith("tools/web/") and e == ".css") else "/*"
    if e in HASH: return "#"
    if e == ".css": return "/*"
    if e in (".html", ".htm"): return "<!--"
    return None

def classify(path):
    """-> (category, style): category is 'own' or a skip reason"""
    if any(path.startswith(v) or path == v.rstrip("/") for v in VENDORED): return "vendored", None
    if any(path.startswith(v) for v in OTHER_SKIP): return "skipped tree", None
    if not any(path.startswith(o) or path == o for o in OWN): return "not source / not ours", None
    st = style(path)
    if st is None: return "data / other type", None
    return "own", st

def line_for(st):
    return {"//": "// " + SPDX, "#": "# " + SPDX, "/*": "/* " + SPDX + " */", "<!--": "<!-- " + SPDX + " -->"}[st]

def process(path, st, write):
    """-> 'has' | 'added' | 'missing' | 'notice' | 'generated' | 'binary'"""
    fp = os.path.join(ROOT, path)
    try:
        raw = open(fp, "rb").read()
        text = raw.decode("utf-8")
    except Exception:
        return "binary"
    if not raw: return "has"                           # an empty marker file (__init__ and the like) needs no header
    nl = "\r\n" if "\r\n" in text[:2000] else "\n"
    lines = text.split("\n")
    if any("SPDX-License-Identifier" in l for l in lines[:4]): return "has"
    if GEN_BANNER.search(lines[0]) or (lines[0].startswith("#!") and len(lines) > 1 and GEN_BANNER.search(lines[1])): return "generated"
    if OWN_NOTICE.search("\n".join(lines[:15])): return "notice"
    i = 0
    if lines[0].startswith("#!"): i = 1
    if st == "#" and len(lines) > i and re.match(r"#.*(coding[:=]|vim?:)", lines[i]): i += 1
    if st == "<!--" and len(lines) > i and re.match(r"\s*<!doctype", lines[i], re.I): i += 1
    if not write: return "missing"
    ins = line_for(st) + ("\r" if nl == "\r\n" else "")
    lines.insert(i, ins)
    open(fp, "wb").write("\n".join(lines).encode("utf-8"))
    return "added"

def main():
    check = "--check" in sys.argv
    report = "--report" in sys.argv
    counts, skipped, bad = {}, {}, {}
    for p in sorted(listing()):
        cat, st = classify(p)
        if cat != "own":
            if os.path.splitext(p)[1] in SLASH + HASH + (".css", ".html") or os.path.basename(p) in ("Makefile", "CMakeLists.txt"):
                skipped.setdefault(cat, []).append(p)
            continue
        r = process(p, st, write=not (check or report))
        counts[r] = counts.get(r, 0) + 1
        if r in ("missing", "generated", "notice"): bad.setdefault(r, []).append(p)
    if report:
        print("own files:", dict(sorted(counts.items())))
        for k, v in sorted(skipped.items()): print("skipped (%s): %d code files" % (k, len(v)))
        for k in ("notice", "generated"):
            for p in bad.get(k, []): print("  %s: %s" % (k, p))
        return 0
    if check:
        # a generated file must carry the line (its generator writes it); a file with its own notice is the owner's call (reported, not failed)
        fail = bad.get("missing", []) + bad.get("generated", [])
        for p in fail: print("spdx: missing on", p)
        print("spdx: %d own files checked, %d missing" % (sum(counts.values()), len(fail)))
        return 1 if fail else 0
    for k in ("notice", "generated"):
        for p in bad.get(k, []): print("spdx: left alone (%s): %s" % (k, p))
    print("spdx: added %d, already present %d" % (counts.get("added", 0), counts.get("has", 0)))
    return 0

sys.exit(main())
